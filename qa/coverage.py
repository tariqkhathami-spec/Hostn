#!/usr/bin/env python3
"""
Contract and coverage report for Hostn.

1. CONTRACT: every API call written in the website and the two apps must
   point at a route the server really serves (right path AND right method).
   A call to a route that does not exist fails the run.
2. COVERAGE: lists which of those calls the end-to-end check (qa/e2e.mjs)
   actually exercised, and which no test has touched yet — so "did we look
   at everything?" has a written answer instead of a feeling.

Run from the repo root, after `node qa/e2e.mjs`:
    python3 qa/coverage.py            # writes qa/COVERAGE.md, exits 1 on a broken call
"""
import collections, glob, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

routes_text = subprocess.run(['node', 'qa/routes.cjs'], capture_output=True, text=True).stdout
routes = [line.split(' ', 1) for line in routes_text.splitlines() if ' ' in line]
if len(routes) < 100:
    sys.exit('Could not read the API routes (run `npm install` in backend/ first).')

def to_regex(path):
    path = re.sub(r':[A-Za-z_]+\??', '[^/]+', path.rstrip('/'))
    return re.compile('^' + path + '/?$')

table = [(method, to_regex(path), path) for method, path in routes]

def match(method, path):
    full = '/api/v1' + path
    for m, rx, original in table:
        if m == method and rx.match(full):
            return original
    return None

CALL = re.compile(r"\bapi\s*\.\s*(get|post|put|patch|delete)\s*(?:<[^>(]*>)?\(\s*([`'\"])((?:(?!\2).|\$\{[^}]*\})*?)\2", re.S)
calls = collections.defaultdict(list)
for app in ('frontend', 'host-app', 'user-app'):
    for f in glob.glob(f'{app}/src/**/*.ts*', recursive=True):
        text = open(f, encoding='utf-8').read()
        for m in CALL.finditer(text):
            path = re.sub(r'\$\{[^}]*\}', 'PARAM', m.group(3)).split('?')[0]
            if not path.startswith('/') or '${' in path or ' ' in path:
                continue
            line = text[:m.start()].count('\n') + 1
            calls[(app, m.group(1).upper(), path)].append(f'{f}:{line}')

hits = set()
if os.path.exists('qa/.hits.json'):
    for h in json.load(open('qa/.hits.json')):
        method, path = h.split(' ', 1)
        route = match(method, path)
        if route:
            hits.add((method, route))

broken, covered, untested = [], [], []
for (app, method, path), where in sorted(calls.items()):
    route = match(method, path)
    if not route:
        broken.append((app, method, path, where[0]))
    elif (method, route) in hits:
        covered.append((app, method, path, where[0]))
    else:
        untested.append((app, method, path, where[0]))

NAMES = {'frontend': 'Website', 'host-app': 'Host app', 'user-app': 'Guest app'}
out = ['# Hostn — API contract and test coverage', '',
       'Generated by `python3 qa/coverage.py`. Do not edit by hand.', '',
       f'- API routes served: **{len(routes)}**',
       f'- Distinct API calls in the website and apps: **{len(calls)}**',
       f'- Calls to a route that does not exist: **{len(broken)}**',
       f'- Calls exercised by the end-to-end check: **{len(covered)}**',
       f'- Calls no automated check has touched: **{len(untested)}**', '']
if broken:
    out += ['## Broken calls (must be zero)', '', '| Where | Call | File |', '|---|---|---|']
    out += [f'| {NAMES[a]} | `{m} {p}` | `{w}` |' for a, m, p, w in broken] + ['']
for app in ('frontend', 'host-app', 'user-app'):
    rows = [(m, p, w) for a, m, p, w in untested if a == app]
    done = sum(1 for a, *_ in covered if a == app)
    out += [f'## {NAMES[app]}: {done} covered, {len(rows)} not yet', '']
    if rows:
        out += ['Not yet exercised by an automated check:', '', '| Call | File |', '|---|---|']
        out += [f'| `{m} {p}` | `{w}` |' for m, p, w in rows] + ['']
open('qa/COVERAGE.md', 'w', encoding='utf-8').write('\n'.join(out) + '\n')

print(f'routes {len(routes)} | calls {len(calls)} | broken {len(broken)} | covered {len(covered)} | untested {len(untested)}')
for a, m, p, w in broken:
    print(f'BROKEN  {NAMES[a]}: {m} {p}  ({w})')
sys.exit(1 if broken else 0)
